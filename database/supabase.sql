-- Run this migration in the Supabase SQL Editor before configuring the PHP API.
CREATE TABLE IF NOT EXISTS public.contacts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL CHECK (btrim(name) <> ''),
    company varchar(255) NOT NULL DEFAULT '',
    phone varchar(255) NOT NULL DEFAULT '',
    email varchar(255) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS contacts_name_sort_idx
    ON public.contacts (lower(name), id DESC);

ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;

-- All data access is performed by the PHP backend using its server-only
-- PostgreSQL connection. Do not grant direct table access to browser roles.
REVOKE ALL ON TABLE public.contacts FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.contacts_id_seq FROM anon, authenticated;
